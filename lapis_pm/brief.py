def _act_merge_pr(target_id: str, pr_number: int | None) -> str:
    """Merge the advisory PR cited by the brief."""
    from agents_core.targets import TargetStore
    try:
        from lapis_pm.pm_core import merge_and_deploy
    except ImportError as exc:
        raise RuntimeError(f"pm_core not available: {exc}") from exc

    store = TargetStore()
    target = store.get(target_id)
    repo = (target.pm_repo if target else None) or ""
    if not repo:
        raise ValueError("target has no pm_repo")
    if pr_number is None:
        raise ValueError("pr_number required for merge_pr action")
    if "/" in repo:
        owner, repo_name = repo.split("/", 1)
    else:
        repo_name, owner = repo, None
    merge_and_deploy(repo_name, pr_number, owner=owner)
    return f"merged PR #{pr_number} in {repo}"


def _act_adopt_pr(target_id: str, pr_number: int | None) -> str:
    """Adopt a deviant-branch PR: set adopted_head_branch + adopted_pr_number, emit observation."""
    from agents_core.targets import TargetStore
    try:
        from agents_core.forgejo import get_pr
    except ImportError as exc:
        raise RuntimeError(f"forgejo not available: {exc}") from exc

    if pr_number is None:
        raise ValueError("pr_number required for adopt_pr action")

    store = TargetStore()
    target = store.get(target_id)
    if target is None:
        raise ValueError(f"target {target_id} not found")

    repo = target.pm_repo or ""
    if "/" in repo:
        owner, repo_name = repo.split("/", 1)
    else:
        repo_name, owner = repo, None

    # Fetch PR details to get head ref
    pr = get_pr(repo_name, pr_number, owner=owner)
    if pr is None:
        raise ValueError(f"PR #{pr_number} not found in {repo}")

    head_ref = (pr.get("head") or {}).get("ref") or ""
    if not head_ref:
        raise ValueError(f"PR #{pr_number} has no head ref")

    # Adopt the PR: set adopted_head_branch and adopted_pr_number
    target.data["adopted_head_branch"] = head_ref
    target.data["adopted_pr_number"] = pr_number
    target.save()

    # Emit observation
    episodic.write_observation(
        target_id,
        f"Adopted orphan PR #{pr_number} on branch {head_ref} into PM loop",
        extra_tags=["pm:orphan-adopted", f"pm:pr={pr_number}"],
    )

    return f"adopted PR #{pr_number} on {head_ref}"


def _act_force_dispatch_retry(target_id: str, brief_comment_id: str) -> str:
    """Force-dispatch fixer referencing the outstanding brief comment."""
    from . import pm_core as _pm
    intent = (
        f"Address outstanding brief comment {brief_comment_id}. "
        "Spec is source of truth."
    )
    task_id = _pm.force_dispatch(target_id, "fixer", intent)
    return f"force_dispatch fixer task_id={task_id}"


def _act_pause_target(target_id: str) -> str:
    """Set paused=true for the target."""
    from . import pm_core as _pm
    _pm.set_pause_state(target_id, "paused")
    from agents_core.targets import TargetStore
    store = TargetStore()
    target = store.get(target_id)
    if target is not None:
        target.set_paused(True, reason="brief option: pause_target")
        target.save()
    return "target paused"


def _act_unbind_target(target_id: str) -> str:
    """Remove pm_bound from the target (hard stop — no further ticks)."""
    from agents_core.targets import TargetStore
    from . import pm_core as _pm
    store = TargetStore()
    target = store.get(target_id)
    if target is not None:
        target.unbind_pm()
        target.save()
    _pm.clear_classified_prs(target_id)
    return "target unbound"


def _act_acknowledge_and_clear(target_id: str) -> str:
    """Informational brief — just clear the outstanding brief."""
    # clear_outstanding_brief is called by apply_decision after this returns.
    # Nothing else to do for acknowledge_and_clear.
    return "acknowledged and cleared"
