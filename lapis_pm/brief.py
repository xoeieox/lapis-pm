"""Brief synthesis + Pushover delivery + closed-form-brief resolution.

Briefs are the PM's user-facing output. They land as `pm:brief` comments and
push a notification with a deep-link to the thread. The body is generated by
the local seat (call_gw_agent, gravitywell-slot1) from spec + recent PM
episodes + the triggering event.

Closed-form briefs also emit a sibling `pm:brief-options` comment (JSON) so
that claude-view can render option buttons. Resolution is via apply_decision()
which is called by both the CLI (brief-resolve) and the tick-loop directive
consumer.

Directive file shape (written by claude-view, consumed by the tick loop):
    {
      "brief_id": "04af254c-...",
      "target_id": "my-target",
      "option_id": "B",
      "ts": "2026-05-02T07:55:00-07:00",
      "submitter": "claude-view"
    }

pm:brief-options comment JSON shape:
    {
      "brief_id": "<comment_id_of_pm:brief_comment>",
      "trigger": "advisory-screen-issue",
      "options": [
        {"id": "A", "label": "...", "action": {"kind": "merge_pr", "pr": 17}},
        {"id": "B", "label": "...", "action": {"kind": "force_dispatch_retry"}},
        {"id": "C", "label": "...", "action": {"kind": "pause_target"}}
      ]
    }
"""

